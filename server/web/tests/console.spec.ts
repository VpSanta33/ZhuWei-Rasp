async function signed(request: APIRequestContext, path: string, value: unknown) {
  const body = JSON.stringify(value), timestamp = String(Date.now()), nonce = randomUUID()
  const digest = createHash('sha256').update(body).digest('hex')
  const signature = createHmac('sha256', app.app.app_secret!).update(`POST\n${path}\n${timestamp}\n${nonce}\n${digest}`).digest('hex')
  const response = await request.post(path, { data: body, headers: { 'Content-Type': 'application/json', 'X-Rasp-AppKey': app.app.app_key, 'X-Rasp-AgentId': agentId, 'X-Rasp-Timestamp': timestamp, 'X-Rasp-Nonce': nonce, 'X-Rasp-Sign': signature } })
  expect(response.ok(), await response.text()).toBeTruthy()
}
